_TRANSLATIONS = {
    "한국어": _KO,
    "English": _EN,
    "日本語": _JA,
    "中文": _ZH,
}

_current_language = None


def get_language() -> str:
    """현재 언어를 반환한다. 최초 호출 시 설정에서 읽어온다."""
    global _current_language
    if _current_language is None:
        try:
            from app.utils.settings_manager import SettingsManager
            lang = SettingsManager().language
        except Exception:
            lang = "한국어"
        _current_language = lang if lang in _TRANSLATIONS else "한국어"
    return _current_language


def set_language(lang: str) -> None:
    """언어를 설정하고 저장한다."""
    global _current_language
    if lang not in _TRANSLATIONS:
        lang = "한국어"
    _current_language = lang
    try:
        from app.utils.settings_manager import SettingsManager
        SettingsManager().language = lang
        SettingsManager().sync()
    except Exception:
        logger.warning("언어 설정 저장 실패", exc_info=True)


def tr(key: str, **kwargs) -> str:
    """키에 해당하는 번역 문자열을 반환한다. 없으면 한국어로 대체한다."""
    lang = get_language()
    text = _TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = _KO.get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text
